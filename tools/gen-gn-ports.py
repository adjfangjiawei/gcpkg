PRE_BUILD = '''    pre_build = function(ctx)
        if not fs.isfile(ctx.src .. '/configure') then
            ctx.exec({ 'autoreconf', '-fi' }, { cwd = ctx.src, log = ctx.log })
        end
    end,
'''


def L(s):
    return json.dumps(str(s), ensure_ascii=False)


def ARR(items, indent=8):
    if not items:
        return "{}"
    pad = " " * indent
    return "{\n" + "".join(pad + L(x) + ",\n" for x in items) + " " * (indent - 2) + "}"


def TBL(d, indent=8):
    if not d:
        return "{}"
    out = "{\n"
    for k, v in d.items():
        key = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else "[" + L(k) + "]"
        out += " " * indent + key + " = " + (ARR(v, indent + 2) if isinstance(v, list) else L(v)) + ",\n"
    return out + " " * (indent - 2) + "}"


def exports_block(e):
    return "\n".join(["    exports = {"] +
                     ["      %s = %s," % (k, ARR(e.get(k, []), 8))
                      for k in ("includes", "libdirs", "libs", "binaries")] +
                     ["    },"])


def build_lua(row):
    name, kind = row["name"], row["kind"]
    meta = META[name]
    deps = [d for d in row["deps"].split(",") if d]
    out = [
        "-- %s %s -- gcpkg port definition." % (name, row["version"]),
        "-- %s" % meta.get("n", ""),
        "",
        'local recipe = require("gcpkg.recipe")',
    ]
    if kind == "autotools":
        out.append('local fs = require("gcpkg.fs")')
    out += ["", "return recipe.%s {" % kind]
    for k in ("name", "version", "license", "homepage"):
        out.append("    %s = %s," % (k, L(row[k])))
    out.append("    description = %s," % L(row["desc"]))
    out += ["    source = {",
            "        url = %s," % L(row["url"]),
            "        sha256 = %s," % L(row["sha256"]),
            "        strip = 1,",
            "    },",
            "    dependencies = %s," % ARR(deps, 8)]
    if kind == "autotools":
        out += ["    autotools = {",
                "        args = %s," % ARR(meta.get("args", []), 10),
                "    },",
                PRE_BUILD.rstrip("\n")]
    elif kind == "cmake":
        out += ["    cmake = {"]
        if meta.get("defines_fn"):
            out.append("        defines = %s," % meta["defines_fn"])
        else:
            defs = dict(BASE_CMAKE)
            defs.update(meta.get("defs", {}))
            out.append("        defines = %s," % TBL(defs, 10))
        out += ["        args = {},"]
        if meta.get("jobs"):
            out.append("        jobs = %d," % meta["jobs"])
        out += ["    },"]
    out.append(exports_block(meta["e"]))
    out.append("}")
    return "\n".join(out) + "\n"


def features_yaml(row):
    meta = META[row["name"]]
    lines = [
        "schema: 1",
        "port: %s" % row["name"],
        "",
        "# %s" % meta.get("n", ""),
        "features:",
        "  no-tests:",
        "    default: true",
        "    description: Skip the upstream test suite",
        "    args: []",
        "  static:",
        "    default: true",
        "    description: Build static libraries",
        "    args: []",
        '    conflicts: ["shared"]',
        "  shared:",
        "    default: false",
        "    description: Build shared libraries",
        "    args: []",
        '    conflicts: ["static"]',
    ]
    for feature, spec in sorted(meta.get("optional", {}).items()):
        requires = spec.get("requires", [])
        lines += [
            "  %s:" % feature,
            "    default: false",
            "    description: %s" % ("Enable %s" % (", ".join(requires) or "this capability")),
            "    requires: [%s]" % ", ".join(requires),
            "    args: %s" % (("[" + ", ".join(L(a) for a in spec.get("args", [])) + "]")
                             if spec.get("args") else "[]"),
        ]
    return "\n".join(lines) + "\n"


def main():
    with open(TSV, newline="") as f:
        rows = [r for r in csv.DictReader(f, delimiter="\t") if r["generator"] == "simple"]
    assert len(rows) == len(META), (len(rows), len(META))
    for row in rows:
        assert row["name"] in META, row["name"]
        d = os.path.join(ROOT, row["name"])
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "build.lua"), "w") as o:
            o.write(build_lua(row))
        with open(os.path.join(d, "features.yaml"), "w") as o:
            o.write(features_yaml(row))
    print("generated %d stock ports into %s" % (len(rows), ROOT))


if __name__ == "__main__":
    main()
