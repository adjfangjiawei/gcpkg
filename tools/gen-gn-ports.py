"""Generate stock-build-system ports for GN-related libraries.

Source of truth: tools/gn-catalog.tsv (28 real upstream tarballs with measured
SHA256, build-system kind and dependency list) plus META below (exported
artifacts, build switches and parallel caps). The engine only reads
ports/<name>/build.lua + features.yaml at runtime. Every port stays exactly
TWO files; upstream sources are never patched.

The seven ports needing custom source()/build() hooks -- gn, ninja, crashpad,
taglib, mongoose, uthash and readerwriterqueue -- are generated by
tools/gen-gn-special-ports.py instead.

    python3 tools/gen-gn-ports.py
    python3 tools/gen-gn-special-ports.py
    ./build/bin/gcpkg check --ports ./ports
"""
