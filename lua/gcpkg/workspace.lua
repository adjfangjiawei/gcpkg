-- new / add / remove / list

function M.new_project(dir, name)
    dir = util.abs(dir)
    name = name or util.basename(dir)
    if fs.isfile(util.join(dir, "gcpkg.yaml")) then
        error("project already exists: " .. dir)
    end
    if not name:match("^[%w_%-%.]+$") then
        error("invalid project name: " .. name)
    end
    fs.mkdirs(dir)
    fs.mkdirs(util.join(dir, "src"))
    fs.mkdirs(util.join(dir, LOCAL_PORTS_DIR))
    fs.write(util.join(dir, "gcpkg.lua"),
             string.format(PROJECT_LUA_TEMPLATE, name, name, name, name))
    fs.write(util.join(dir, "gcpkg.yaml"), render({}, name))
    fs.write(util.join(dir, "src", "main.c"), string.format(MAIN_C_TEMPLATE, name))
    fs.write(util.join(dir, LOCAL_PORTS_DIR, "README.md"), LOCAL_PORTS_README)
    fs.write(util.join(dir, ".gitignore"), PROJECT_GITIGNORE)
    return dir
end

-- Effective dependency list for a project: gcpkg.lua + gcpkg.yaml + opted-in
-- global dependencies. Duplicates (same name) keep the FIRST, project wins.
function M.effective_dependencies(projectDir, y, storeRoot, luaSpec)
    local out, seen = {}, {}
    local function push(spec)
        local name = M.dep_name(spec)
        if not seen[name] then
            seen[name] = true
            out[#out + 1] = M.dep_string(spec)
        end
    end
    for _, d in ipairs((luaSpec or {}).dependencies or {}) do
        push(d)
    end
    for _, d in ipairs(M.dependencies(y)) do
        push(d)
    end
    for _, d in ipairs(M.global_dependencies(storeRoot, y.inherit_global)) do
        push(d)
    end
    return out
end

function M.add(projectDir, specs, opts)
    opts = opts or {}
    local roots = opts.roots or {}
    local target, fallback
    if opts.global then
        target = M.global_yaml_path(opts.storeRoot)
        fallback = "global"
        projectDir = nil
    else
        if not projectDir then
            error("not inside a gcpkg project (no gcpkg.yaml found); run `gcpkg new DIR` first")
        end
        target = util.join(projectDir, "gcpkg.yaml")
        fallback = util.basename(projectDir)
    end
    local y = M.read_yaml(target)
    local deps = M.dependencies(y)
    local log = require("gcpkg.log")
    for _, raw in ipairs(specs) do
        local name, wanted = M.dep_name(raw), M.dep_version(raw)
        -- A brand-new private port has no declared versions yet; the user fills
        -- in build.lua/features.yaml. Public ports are checked strictly.
        if not opts.local_port then
            M.validate_version(name, wanted, roots)
        end
        local dep = M.dep_string(raw)
        local replaced = false
        for i, old in ipairs(deps) do
            if M.dep_name(old) == name then
                deps[i] = dep
                replaced = true
                break
            end
        end
        if not replaced then
            deps[#deps + 1] = dep
        end
        local scope = opts.local_port and "project (private port)" or
                      M.scope_of(port.find(name, roots), projectDir)
        if opts.local_port and not opts.global then
            local dst = util.join(projectDir, LOCAL_PORTS_DIR, name)
            local src = port.find(name, roots)
            if fs.isfile(util.join(dst, "build.lua")) then
                log.info("private port already exists: " .. dst)
            else
                local how = M.scaffold_port(dst, name, src)
                log.step("created project-private port " .. dst .. " (" .. how .. ")")
            end
            if wanted then
                log.warn("private port " .. name .. ": declare " .. wanted ..
                         " in " .. util.join(dst, "features.yaml") .. " `versions:`")
            end
        end
        log.info(string.format("added %-24s scope=%s%s", dep, scope,
                               replaced and " (replaced previous version)" or ""))
    end
    local normalized
    if opts.global then
        normalized = M.set_global_dependencies(opts.storeRoot, deps)
    else
        normalized = M.set_dependencies(target, deps, fallback)
    end
    if normalized then
        log.warn("normalised " .. target .. " (comments outside the managed block were dropped)")
    end
    M.write_lock_from_yaml(projectDir, target, M.read_yaml(target), opts)
    return deps
end

function M.remove(projectDir, specs, opts)
    opts = opts or {}
    local target, fallback
    if opts.global then
        target = M.global_yaml_path(opts.storeRoot)
        fallback = "global"
        projectDir = nil
    else
        if not projectDir then
            error("not inside a gcpkg project (no gcpkg.yaml found)")
        end
        target = util.join(projectDir, "gcpkg.yaml")
        fallback = util.basename(projectDir)
    end
    local y = M.read_yaml(target)
    local deps = M.dependencies(y)
    local log = require("gcpkg.log")
    for _, raw in ipairs(specs) do
        local name = M.dep_name(raw)
        local kept = {}
        for _, d in ipairs(deps) do
            if M.dep_name(d) ~= name then
                kept[#kept + 1] = d
            else
                log.info("removed " .. d)
            end
        end
        deps = kept
    end
    if opts.global then
        M.set_global_dependencies(opts.storeRoot, deps)
    else
        M.set_dependencies(target, deps, fallback)
    end
    M.write_lock_from_yaml(projectDir, target, M.read_yaml(target), opts)
    return deps
end

function M.list(projectDir, opts)
    opts = opts or {}
    local log = require("gcpkg.log")
    local target = util.join(projectDir, "gcpkg.yaml")
    local y = M.read_yaml(target)
    local deps = M.dependencies(y)
    local global = M.dependencies(M.read_yaml(M.global_yaml_path(opts.storeRoot)))
    local roots = opts.roots or {}
    log.step("project " .. tostring(y.project or util.basename(projectDir)) ..
             " (" .. projectDir .. ")")
    log.info("  inherit_global : " .. tostring(y.inherit_global == true))
    log.info("  port roots     : " .. tostring(#roots))
    log.info("  dependencies   : " .. #deps .. " (project-specific)")
    for _, d in ipairs(deps) do
        local dir = port.find(M.dep_name(d), roots)
        local avail, default = {}, nil
        if dir then
            avail, default = M.available_versions(dir)
        end
        local v = M.dep_version(d)
        local resolved = v or default or "?"
        log.info(string.format("    - %-24s version=%-10s %-8s port=%s", d,
            tostring(resolved), "[" .. M.scope_of(dir, projectDir) .. "]",
            tostring(dir or "NOT FOUND")))
        if v and not avail[v] and v ~= default then
            log.warn("      requested version " .. v .. " is not declared in this port")
        end
    end
    log.info("  global deps    : " .. #global ..
             (y.inherit_global == true and " (inherited)" or " (not inherited)"))
    for _, d in ipairs(global) do
        log.info("    - " .. d)
    end
    local locked = M.read_lock(projectDir)
    if locked then
        log.info("  lock           : " .. M.lock_path(projectDir) ..
                 " (" .. #(locked.resolved or {}) .. " resolved libraries)")
        for _, r in ipairs(locked.resolved or {}) do
            log.info(string.format("    = %-24s %-8s compdb=%s", r.key or "?",
                "[" .. (r.scope or "?") .. "]", tostring(r.compdb_entries or 0)))
        end
    else
        log.info("  lock           : (none yet; build or install the project)")
    end
end

--------------------------------------------------------------------------------
-- lock file

function M.lock_path(projectDir)
    return util.join(projectDir, "gcpkg.lock")
end

-- json.encode() emits {} for an empty Lua table; a lock's `resolved` field
-- is conceptually a list, so keep it as [] for readers and diff tools.
local function encode_lock(value)
    local text = json.encode(value, true)
    if #(value.resolved or {}) == 0 then
        text = text:gsub('"resolved": {}', '"resolved": []')
    end
    return text .. "\n"
end

function M.read_lock(projectDir)
    local text = fs.read(M.lock_path(projectDir))
    if not text then
        return nil
    end
    local ok, value = pcall(json.decode, text)
    if ok and type(value) == "table" then
        return value
    end
    return nil
end

-- Locks are meant to be committed, so keep machine-local paths portable:
-- inside the project -> ./..., under $HOME -> ~/...
local function portable(p, projectDir)
    if type(p) ~= "string" then
        return p
    end
    if projectDir and util.startswith(p, projectDir .. "/") then
        return "./" .. p:sub(#projectDir + 2)
    end
    local home = gcpkg.sys.getenv("HOME")
    if home and util.startswith(p, home .. "/") then
        return "~/" .. p:sub(#home + 2)
    end
    return p
end

local function describe_manifests(ordered, roots, projectDir)
    local out = {}
    for _, m in ipairs(ordered or {}) do
        local dir = port.find(m.name, roots)
        out[#out + 1] = {
            name = m.name, version = m.version, key = m.key,
            scope = M.scope_of(dir, projectDir),
            port_dir = portable(dir, projectDir),
            compdb_entries = m.compdb_entries or 0,
            prefix = portable(m.prefix, projectDir),
        }
    end
    return out
end

function M.write_lock(projectDir, y, cfg, ordered, luaSpec)
    if not projectDir then
        return
    end
    local deps = M.effective_dependencies(projectDir, y,
        cfg.store and cfg.store.root, luaSpec)
    local roots = cfg.ports or port.get_roots()
    local value = {
        schema = 1,
        project = y.project or util.basename(projectDir),
        dependencies = deps,
        inherit_global = y.inherit_global == true,
        ports = util.map(cfg.ports or {}, function(r)
            return portable(r, projectDir)
        end),
        store = portable(cfg.store and cfg.store.root, projectDir),
        resolved = describe_manifests(ordered, roots, projectDir),
        fingerprint = require("gcpkg.store").fingerprint(deps),
    }
    fs.write(M.lock_path(projectDir), encode_lock(value))
    return value
end

-- `add` / `remove` invalidate the lock: keep the desired dependency list,
-- drop the resolved set until the next build/install.
function M.write_lock_from_yaml(projectDir, target, y, opts)
    if not projectDir then
        return
    end
    local value = {
        schema = 1,
        project = y.project or util.basename(projectDir),
        dependencies = M.effective_dependencies(projectDir, y, opts.storeRoot),
        inherit_global = y.inherit_global == true,
        ports = util.map(opts.roots or {}, function(r)
            return portable(r, projectDir)
        end),
        resolved = {},
        pending = true,
    }
    fs.write(M.lock_path(projectDir), encode_lock(value))
    return value
end

-- Load gcpkg.lua of a project without requiring gcpkg.project (no cycle).
function M.load_lua_spec(projectDir)
    local path = util.join(projectDir, "gcpkg.lua")
    if not fs.isfile(path) then
        return {}
    end
    local ok, spec = pcall(gcpkg.sys.loadchunk, path)
    if ok and type(spec) == "table" then
        return spec
    end
    return {}
end

-- `gcpkg install` with no argument: install a project's declared libraries
-- only (no project sources), then refresh its lock file.
function M.install_project(projectDir, cfg)
    local y = M.read_yaml(util.join(projectDir, "gcpkg.yaml"))
    local luaSpec = M.load_lua_spec(projectDir)
    -- Same merge rule as gcpkg.project.build: project YAML features are
    -- applied on top of CLI --feature requests. from_yaml() returns a map of
    -- port -> {enable={feature names}, disable={...}}, so re-add them with the
    -- explicit "port:feature" form rather than treating them as globals.
    local requests = util.deepcopy(cfg.requests or {})
    local fromYaml = features.from_yaml(y)
    for _, portName in ipairs(util.keys(fromYaml)) do
        local entry = fromYaml[portName]
        for _, f in ipairs(entry.enable or {}) do
            features.add_request(requests, portName .. ":" .. f)
        end
        for _, f in ipairs(entry.disable or {}) do
            features.add_request(requests, "-" .. portName .. ":" .. f)
        end
    end
    local roots = M.roots(projectDir, cfg.ports or port.get_roots(), y)
    local sub = util.merge(cfg, { requests = requests, ports = roots })
    local deps = M.effective_dependencies(projectDir, y,
        cfg.store and cfg.store.root, luaSpec)
    local log = require("gcpkg.log")
    local manifests = {}
    for _, d in ipairs(deps) do
        manifests[#manifests + 1] = port.install_or_backend(d, sub)
    end
    local ordered = port.transitive(manifests, cfg.store)
    M.write_lock(projectDir, y, sub, ordered, luaSpec)
    log.step(#deps .. " project dependencies installed; " ..
             "lock written to " .. M.lock_path(projectDir))
    return ordered
end

return M
