-- versions

function M.available_versions(dir)
    local ok, spec = pcall(port.load, dir)
    if not ok or type(spec) ~= "table" then
        return {}, nil
    end
    local fspec = port.features_file(dir) or {}
    local default = spec.version and tostring(spec.version) or nil
    local out = {}
    if default then
        out[default] = {
            version = default, default = true, origin = "build.lua",
            source = spec.source,
        }
    end
    for v, def in pairs(fspec.versions or {}) do
        local key = tostring(v)
        local src = type(spec.source) == "table" and util.deepcopy(spec.source) or {}
        if type(def) == "table" then
            if type(def.source) == "table" then
                src = util.merge(src, def.source)
            elseif def.url or def.sha256 then
                src = util.merge(src, { url = def.url, sha256 = def.sha256 })
            end
        end
        out[key] = {
            version = key, default = (key == default), origin = "features.yaml",
            source = src, dependencies = type(def) == "table" and def.dependencies or nil,
        }
    end
    return out, default
end

function M.validate_version(name, wanted, roots)
    if not wanted then
        return
    end
    local dir = port.find(name, roots)
    if not dir then
        error("port '" .. name .. "' not found; use `gcpkg add --local " .. name ..
              "` to scaffold a project-private port")
    end
    local available, default = M.available_versions(dir)
    if available[wanted] then
        return
    end
    if default == wanted then
        return
    end
    local list = util.keys(available)
    error("port '" .. name .. "' has no version '" .. wanted .. "'. Available: " ..
          (#list > 0 and table.concat(list, ", ") or "(none declared)") ..
          ". Add one to " .. util.join(dir, "features.yaml") .. " under `versions:`.")
end

function M.describe_versions(name, roots)
    local dir = port.find(name, roots)
    if not dir then
        error("port '" .. name .. "' not found")
    end
    local available, default = M.available_versions(dir)
    local log = require("gcpkg.log")
    log.step("versions of " .. name .. " (port: " .. dir .. "):")
    for _, v in ipairs(util.keys(available)) do
        local e = available[v]
        local src = type(e.source) == "table" and (e.source.url or e.source.git or e.source.dir) or "-"
        log.info(string.format("  %s %-10s %-14s %s",
            (v == default) and "*" or " ", v, "[" .. e.origin .. "]", tostring(src)))
    end
    if next(available) == nil then
        log.info("  (no version declared)")
    end
    return available
end

