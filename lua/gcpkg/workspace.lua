-- minimal YAML writer (enough for gcpkg.yaml; the managed block is text)

local function scalar(v)
    if type(v) == "boolean" then
        return v and "true" or "false"
    end
    if type(v) == "number" then
        return tostring(v)
    end
    if v == nil then
        return "null"
    end
    local s = tostring(v)
    if s == "" then
        return '""'
    end
    if s:match("^[%w_./@%+%-:]+$") and not s:match("^%d+$") and
       s ~= "true" and s ~= "false" and s ~= "null" then
        return s
    end
    return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
end

local function inline_list(t)
    local parts = {}
    for _, v in ipairs(t or {}) do
        if type(v) == "table" then
            parts[#parts + 1] = "{}"
        else
            parts[#parts + 1] = scalar(v)
        end
    end
    return "[" .. table.concat(parts, ", ") .. "]"
end

local function dump_table(t, indent, out)
    out = out or {}
    local pad = string.rep(" ", indent)
    for _, k in ipairs(util.keys(t)) do
        local v = t[k]
        if type(v) == "table" then
            if v[1] ~= nil then
                local scalars = true
                for _, x in ipairs(v) do
                    if type(x) == "table" then
                        scalars = false
                    end
                end
                if scalars then
                    out[#out + 1] = pad .. tostring(k) .. ": " .. inline_list(v)
                else
                    out[#out + 1] = pad .. tostring(k) .. ":"
                    for _, x in ipairs(v) do
                        dump_table(x, indent + 2, out)
                    end
                end
            elseif next(v) == nil then
                out[#out + 1] = pad .. tostring(k) .. ": {}"
            else
                out[#out + 1] = pad .. tostring(k) .. ":"
                dump_table(v, indent + 2, out)
            end
        else
            out[#out + 1] = pad .. tostring(k) .. ": " .. scalar(v)
        end
    end
    return out
end

local function dependencies_block(deps)
    local out = { M.DEP_START }
    if #deps == 0 then
        out[#out + 1] = "dependencies: []"
    else
        out[#out + 1] = "dependencies:"
        for _, d in ipairs(deps) do
            out[#out + 1] = "  - " .. scalar(d)
        end
    end
    out[#out + 1] = M.DEP_END
    return out
end

local function render_list(v)
    if type(v) == "table" then
        if v[1] ~= nil then return v end
        return util.keys(v)
    end
    local out = {}
    for part in tostring(v or ""):gmatch("[^,%s]+") do out[#out + 1] = part end
    return out
end

local function render(y, fallbackName)
    local roots = y.ports or { LOCAL_PORTS_DIR }
    if type(roots) == "string" then
        roots = { roots }
    end
    local out = {
        "schema: 1",
        "project: " .. scalar(y.project or fallbackName or "project"),
        "version: " .. scalar(y.version or "0.1.0"),
        "inherit_global: " .. (y.inherit_global == true and "true" or "false"),
        "",
        "# Port search roots. Project-local ports take precedence over public ones.",
        "ports: " .. inline_list(roots),
        "",
    }
    local block = dependencies_block(M.dependencies(y))
    for _, line in ipairs(block) do
        out[#out + 1] = line
    end
    out[#out + 1] = ""
    out[#out + 1] = "# Project-level feature selection (see `gcpkg features PORT`)."
    local f = y.features
    if type(f) ~= "table" or next(f) == nil then
        out[#out + 1] = "features: {}"
    elseif f[1] ~= nil then
        -- list form: features: [openssl:shared, -openssl:no-tests]
        out[#out + 1] = "features: " .. inline_list(f)
    else
        out[#out + 1] = "features:"
        dump_table(f, 2, out)
    end
    -- managed workspace: preserve the OUTER/INNER split.  `gcpkg add/remove` rewrites the
    -- managed dependency block but must never drop the project's own build
    -- system declaration or its Conan command configuration.
    out[#out + 1] = ""
    out[#out + 1] = "# Inner build systems managed by gcpkg (auto / cmake / gn / meson / conan / canon alias / makefile / ninja)."
    if y.system ~= nil then
        out[#out + 1] = "system: " .. (type(y.system) == "table" and json.encode(y.system) or scalar(y.system))
    end
    if y.systems ~= nil then out[#out + 1] = "systems: " .. json.encode(render_list(y.systems)) end
    if y.install_prefix ~= nil then out[#out + 1] = "install_prefix: " .. scalar(y.install_prefix) end
    if y.build_dir ~= nil then out[#out + 1] = "build_dir: " .. scalar(y.build_dir) end
    if y.conan_cmd ~= nil then
        local cmd = y.conan_cmd
        if type(cmd) == "string" then cmd = util.shellsplit(cmd) end
        out[#out + 1] = "conan_cmd: " .. json.encode(cmd)
    end
    if y.canon_cmd ~= nil then
        local cmd = y.canon_cmd
        if type(cmd) == "string" then cmd = util.shellsplit(cmd) end
        out[#out + 1] = "canon_cmd: " .. json.encode(cmd)
    end
    if type(y.commands) == "table" then
        out[#out + 1] = "commands: " .. json.encode(y.commands)
    end
    if type(y.projects) == "table" then
        out[#out + 1] = "projects: " .. json.encode(y.projects)
    end
    return table.concat(out, "\n") .. "\n"
end

-- Replace ONLY the managed block when present; otherwise normalise the file
-- (keeps project/version/features, drops comments -- `gcpkg add` tells you).
function M.set_dependencies(path, deps, fallbackName)
    local text = fs.read(path)
    local normalized = false
    -- util.lines() drops blank lines; split() preserves them so editing the
    -- managed block does not silently compact the rest of gcpkg.yaml.
    local lines = text and util.split(text, "\n") or {}
    local s, e
    for i, line in ipairs(lines) do
        if util.trim(line) == M.DEP_START then
            s = i
        elseif util.trim(line) == M.DEP_END then
            e = i
        end
    end
    local result
    if s and e and e > s then
        local block = dependencies_block(deps)
        result = {}
        for i = 1, s - 1 do
            result[#result + 1] = lines[i]
        end
        for _, line in ipairs(block) do
            result[#result + 1] = line
        end
        for i = e + 1, #lines do
            result[#result + 1] = lines[i]
        end
    else
        local y = text and M.read_yaml(path) or {}
        y.dependencies = deps
        result = util.split(render(y, fallbackName), "\n")
        normalized = true
    end
    while #result > 0 and result[#result] == "" do
        table.remove(result)
    end
    fs.mkdirs(util.dirname(path))
    fs.write(path, table.concat(result, "\n") .. "\n")
    return normalized
end

function M.set_global_dependencies(storeRoot, deps)
    local path = M.global_yaml_path(storeRoot)
    if not fs.isfile(path) then
        local head = {
            "schema: 1",
            "# Global (public) dependencies: `gcpkg add -g NAME`. A project only",
            "# inherits these when its gcpkg.yaml sets inherit_global: true.",
        }
        for _, line in ipairs(dependencies_block({})) do
            head[#head + 1] = line
        end
        fs.mkdirs(util.dirname(path))
        fs.write(path, table.concat(head, "\n") .. "\n")
    end
    return M.set_dependencies(path, deps, "global")
end

