-- paths / roots

function M.home()
    return gcpkg.sys.getenv("GCPKG_HOME") or
           util.join(gcpkg.sys.getenv("HOME") or fs.cwd(), ".gcpkg")
end

function M.user_ports_root()
    return util.join(M.home(), "ports")
end

function M.global_yaml_path(storeRoot)
    return util.join(storeRoot or M.home(), "gcpkg.yaml")
end

-- Walk upwards looking for gcpkg.yaml, like pnpm looking for package.json.
function M.find_root(startDir)
    local dir = util.abs(startDir or fs.cwd())
    for _ = 1, 10 do
        if fs.isfile(util.join(dir, "gcpkg.yaml")) then
            return dir
        end
        local parent = util.dirname(dir)
        if parent == dir then
            break
        end
        dir = parent
    end
    return nil
end

function M.read_yaml(path)
    local text = fs.read(path)
    if not text then
        return nil
    end
    local ok, value = pcall(yaml.parse, text)
    if ok and type(value) == "table" then
        return value
    end
    return {}
end

-- Ordered port search roots. `base` comes from the CLI (--ports / defaults).
function M.roots(projectDir, base, y)
    local out = {}
    if projectDir then
        local listed = (y or {}).ports or { LOCAL_PORTS_DIR }
        if type(listed) == "string" then
            listed = { listed }
        end
        for _, p in ipairs(listed or {}) do
            local d = util.abs(tostring(p), projectDir)
            if fs.isdir(d) then
                out[#out + 1] = d
            end
        end
        -- Auto-detect the conventional directory even if `ports:` is absent.
        local auto = util.join(projectDir, LOCAL_PORTS_DIR)
        if fs.isdir(auto) and not util.contains(out, auto) then
            out[#out + 1] = auto
        end
    end
    out[#out + 1] = M.user_ports_root()
    for _, r in ipairs(base or {}) do
        out[#out + 1] = r
    end
    return util.uniq(out)
end

function M.scope_of(dir, projectDir)
    if not dir then
        return "missing"
    end
    if projectDir and util.startswith(dir, util.join(projectDir, LOCAL_PORTS_DIR) .. "/") then
        return "project"
    end
    if util.startswith(dir, M.user_ports_root() .. "/") then
        return "user"
    end
    return "public"
end

