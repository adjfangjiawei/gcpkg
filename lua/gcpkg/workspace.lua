-- Project workspace: pnpm-style `new` / `add` / `remove` / `list`.
--
-- Three scopes, searched in this order (first match wins):
--   1. project  : <project>/gcpkg-ports/<name>/   (private to ONE project)
--   2. user     : $GCPKG_HOME/ports/<name>/       (your own shared libraries)
--   3. public   : --ports / GCPKG_PORTS / engine share/ports / cwd/ports
--
-- Dependencies themselves also come in two scopes:
--   * project  : <project>/gcpkg.yaml `dependencies` (per-project, the default)
--   * global   : $GCPKG_HOME/gcpkg.yaml `dependencies`; a project only sees
--                them when it opts in with `inherit_global: true`.
-- This keeps different projects on different libraries AND different versions.
-- `gcpkg.lock` records what was actually resolved for each project.
local util = require("gcpkg.util")
local fs = require("gcpkg.fs")
local yaml = require("gcpkg.yaml")
local json = require("gcpkg.json")
local features = require("gcpkg.features")
local port = require("gcpkg.port")

local M = {}

M.DEP_START = "# --- gcpkg managed dependencies (use `gcpkg add` / `gcpkg remove`) ---"
M.DEP_END = "# --- end gcpkg managed dependencies ---"

local LOCAL_PORTS_DIR = "gcpkg-ports"

local PORT_TEMPLATE = [[-- %s: ONE build description for ONE library.
-- Project-private port: lives in gcpkg-ports/, overrides the public registry.
local make = require("gcpkg.build.make")

return {
  name = "%s",
  version = "0.0.0",
  source = {
    url = "https://example.com/%s-0.0.0.tar.gz",
    sha256 = nil,
    strip = 1,
  },
  dependencies = {},

  build = function(ctx)
    ctx.exec({ "./configure", "--prefix=" .. ctx.prefix })
    make.install({ cwd = ctx.src, exec = ctx.exec, log = ctx.log, jobs = ctx.jobs })
    return {
      includes = { ctx.prefix .. "/include" },
      libdirs  = { ctx.prefix .. "/lib" },
      libs     = { "%s" },
    }
  end,
}
]]

local PORT_FEATURES_TEMPLATE = [[schema: 1
port: %s
# ONE feature description per library. Add a `versions:` block here to offer
# several upstream releases: versions: {"1.2.3": {source: {url: ..., sha256: ...}}}
features:
  shared:
    default: false
    description: build shared libraries
]]

