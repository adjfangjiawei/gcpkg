-- Build description stays in Lua; the dependency LIST lives in gcpkg.yaml's
-- managed block so `gcpkg add` / `gcpkg remove` can edit it safely.
local cc = require("gcpkg.build.cc")

return {
    name = "%s",
    version = "0.1.0",
    dependencies = {},

    build = function(ctx)
        local objects = cc.compile {
            sources = { "src/main.c" },
            includes = ctx.includes,
            defines = ctx.defines,
            flags = { "-std=c11", "-O2", "-g", "-Wall" },
            outdir = ctx.build_dir .. "/obj",
            cwd = ctx.project_dir,
            compiler = ctx.compiler.cc,
            exec = ctx.exec,
            record = ctx.record,
            log = ctx.log,
            tag = "%s",
        }
        local binary = cc.link {
            objects = objects,
            output = ctx.build_dir .. "/%s",
            libdirs = ctx.libdirs,
            libs = ctx.libs,
            flags = ctx.link_flags,
            cwd = ctx.project_dir,
            compiler = ctx.compiler.cc,
            exec = ctx.exec,
            log = ctx.log,
        }
        gcpkg.log.step("built " .. binary)
        return {}
