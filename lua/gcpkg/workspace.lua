-- dependency specs: "name", "name@version", {name=,version=}, map {name=version}

function M.dep_name(spec)
    if type(spec) == "table" then
        return tostring(spec.name or spec[1])
    end
    return (tostring(spec):gsub("@.*$", ""))
end

function M.dep_version(spec)
    if type(spec) == "table" then
        return spec.version and tostring(spec.version) or nil
    end
    return tostring(spec):match("^[^@]+@(.+)$")
end

function M.dep_string(spec)
    local v = M.dep_version(spec)
    local n = M.dep_name(spec)
    return v and (n .. "@" .. v) or n
end

function M.dependencies(y)
    local d = (y or {}).dependencies
    local out = {}
    if type(d) == "table" then
        if d[1] ~= nil then
            for _, item in ipairs(d) do
                out[#out + 1] = M.dep_string(item)
            end
        else
            -- map form: { zlib = "1.2.13" } -> zlib@1.2.13
            for _, name in ipairs(util.keys(d)) do
                local v = d[name]
                if v == nil or v == true then
                    out[#out + 1] = name
                elseif type(v) == "table" then
                    out[#out + 1] = M.dep_string(util.merge({ name = name }, v))
                else
                    out[#out + 1] = name .. "@" .. tostring(v)
                end
            end
        end
    elseif type(d) == "string" then
        out[1] = d
    end
    return out
end

function M.global_dependencies(storeRoot, inherit)
    if inherit ~= true then
        return {}
    end
    return M.dependencies(M.read_yaml(M.global_yaml_path(storeRoot)))
end

