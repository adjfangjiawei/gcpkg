-- port scaffolding (also used by `gcpkg port new`)

function M.scaffold_port(dir, name, sourceDir)
    fs.mkdirs(dir)
    if sourceDir and fs.isfile(util.join(sourceDir, "build.lua")) then
        fs.copy(util.join(sourceDir, "build.lua"), util.join(dir, "build.lua"))
        if fs.isfile(util.join(sourceDir, "features.yaml")) then
            fs.copy(util.join(sourceDir, "features.yaml"), util.join(dir, "features.yaml"))
        else
            fs.write(util.join(dir, "features.yaml"),
                     string.format(PORT_FEATURES_TEMPLATE, name))
        end
        return "copied from " .. sourceDir
    end
    fs.write(util.join(dir, "build.lua"),
             string.format(PORT_TEMPLATE, name, name, name, name))
    fs.write(util.join(dir, "features.yaml"),
             string.format(PORT_FEATURES_TEMPLATE, name))
    return "new private port (edit source url/sha256 in build.lua)"
end

