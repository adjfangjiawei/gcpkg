-- lyra 1.7.0 -- R20 new-standard header-only port.
--
-- A composing command-line argument parser for C++11 and later.
--
-- Upstream ships THREE build systems: CMake (deliberately minimal: no tests, no
-- options, only an INTERFACE target plus install rules), Meson (headers + a
-- generated .pc), and B2 (the real test suite, tests/build.jam).  There is not
-- a single option to expose, so the feature layer here is built from what the
-- port can actually verify rather than from upstream switches:
--
--   tests         - the whole B2 test suite, reproduced with CMake/CTest from
--                   upstream's own sources: every tests/*_run_test.cpp becomes
--                   one registered CTest program (B2's `run`), and the
--                   compile-only programs (B2's `compile`: base_compile_test,
--                   single_include_test against data/single_include,
--                   issue_93_test) each get a CTest entry that builds them.
--   lib-use-test  - tests/lib_use_test, upstream's own external-project check:
--                   a separate CMake project that does find_package(lyra
--                   REQUIRED) and links bfg::lyra against the INSTALLED tree.
--   pkgconfig     - the .pc file upstream's Meson build generates
--                   (install_headers + pkg.generate), written here for CMake
--                   installs, which upstream does not provide.
--   cmake-package - assert upstream's lyraConfig.cmake / lyraTarget.cmake.
local recipe = require("gcpkg.recipe")
local fs = require("gcpkg.fs")
local util = require("gcpkg.util")
local cc = require("gcpkg.build.cc")

local VERSION = "1.7.0"

-- Read one whitespace-free item per line from a file produced by `ls`.
local function read_list(path)
    local text = fs.read(path) or ""
    local out = {}
    for line in text:gmatch("[^\r\n]+") do
        line = line:gsub("^%s+", ""):gsub("%s+$", "")
        if line ~= "" then out[#out + 1] = line end
    end
    return out
end

local function basename(path, suffix)
    local b = path:match("[^/]+$") or path
    if suffix then b = b:gsub(suffix .. "$", "") end
    return b
end

-- Reproduce upstream's tests/build.jam with CMake + CTest:
--   `run`     -> one registered test program per *_run_test.cpp
--   `compile` -> one CTest entry that builds the compile-only program
local function run_upstream_tests(ctx)
    local testsdir = util.join(ctx.src, "tests")
    ctx.exec({ "sh", "-c", "ls " .. testsdir .. "/*_run_test.cpp > run_list.txt" },
             { cwd = ctx.build_dir, log = ctx.log })
    local run_tests = read_list(util.join(ctx.build_dir, "run_list.txt"))
    assert(#run_tests >= 45,
           "gcpkg: lyra: expected ~50 upstream run tests, found " .. #run_tests)

    -- optional_type_test.cpp is `run` in build.jam outside the glob, and the
    -- three `compile` targets are listed by name there as well.
    table.insert(run_tests, util.join(testsdir, "optional_type_test.cpp"))
    local compile_tests = {
        { src = util.join(testsdir, "base_compile_test.cpp") },
        { src = util.join(testsdir, "single_include_test.cpp"),
          extra_include = util.join(ctx.src, "data/single_include") },
        { src = util.join(testsdir, "issue_93_test.cpp") },
    }

    local driver = util.join(ctx.build_dir, "upstream-tests")
    fs.mkdirs(driver)
    local lines = {
        "# Generated by the gcpkg lyra port: upstream's tests/build.jam, expressed",
        "# as a CMake project so the suite runs through CTest.",
        "cmake_minimum_required(VERSION 3.16)",
        "project(lyra-upstream-tests LANGUAGES CXX)",
        "enable_testing()",
        'set(LYRA_INC "' .. tostring(ctx.src) .. '/include")',
        'set(LYRA_EXAMPLES "' .. tostring(ctx.src) .. '/examples")',
        'set(LYRA_TESTS "' .. tostring(ctx.src) .. '/tests")',
        "set(CMAKE_CXX_STANDARD 17)",
        "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        "",
    }
    for _, src in ipairs(run_tests) do
        local name = basename(src, ".cpp")
        lines[#lines + 1] = "add_executable(" .. name .. " \"" .. src .. "\")"
        lines[#lines + 1] = "target_include_directories(" .. name ..
                            " PRIVATE ${LYRA_INC} ${LYRA_EXAMPLES} ${LYRA_TESTS})"
        lines[#lines + 1] = "add_test(NAME " .. name .. " COMMAND " .. name .. ")"
        lines[#lines + 1] = ""
    end
    for _, t in ipairs(compile_tests) do
        local name = basename(t.src, ".cpp")
        -- B2's `compile` produces only an object file: these programs have no
        -- main() (base_compile_test.cpp has none at all), so they are OBJECT
        -- libraries that the CTest entry builds, not links.
        lines[#lines + 1] = "# compile-only, as in build.jam: `compile " .. name .. ".cpp`"
        lines[#lines + 1] = "add_library(" .. name .. " OBJECT EXCLUDE_FROM_ALL \"" ..
                            t.src .. "\")"
        local incs = "${LYRA_INC} ${LYRA_EXAMPLES} ${LYRA_TESTS}"
        if t.extra_include then incs = incs .. ' "' .. t.extra_include .. '"' end
        lines[#lines + 1] = "target_include_directories(" .. name ..
                            " PRIVATE " .. incs .. ")"
        lines[#lines + 1] = "add_test(NAME " .. name .. " COMMAND " ..
                            "${CMAKE_COMMAND} --build ${CMAKE_BINARY_DIR} --target " ..
                            name .. ")"
        lines[#lines + 1] = ""
    end
    fs.write(util.join(driver, "CMakeLists.txt"), table.concat(lines, "\n") .. "\n")

    local dbuild = util.join(driver, "build")
    ctx.exec({ "cmake", "-S", driver, "-B", dbuild,
               "-DCMAKE_BUILD_TYPE=Release",
               "-DCMAKE_CXX_COMPILER=" .. tostring(ctx.compiler.wrapper_cxx) },
             { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
    ctx.exec({ "cmake", "--build", dbuild, "--parallel", tostring(ctx.jobs or 4) },
             { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })

    local out = util.join(ctx.build_dir, "ctest.out")
    ctx.exec({ "sh", "-c",
               "cd " .. dbuild .. " && ctest --output-on-failure > " .. out ..
               " 2>&1; echo $? > " .. out .. ".rc" },
             { cwd = dbuild, log = ctx.log, env = ctx.env })
    local rc = (fs.read(out .. ".rc") or "?"):gsub("%s", "")
    local text = assert(fs.read(out), "gcpkg: lyra: missing ctest output")
    assert(not text:find("No tests were found", 1, true),
           "gcpkg: lyra: ctest found no registered tests")
    assert(text:find("100% tests passed", 1, true),
           "gcpkg: lyra: upstream test suite did not pass: " .. text)
    assert(rc == "0", "gcpkg: lyra: ctest exited with " .. rc)
    local registered = tonumber(text:match("out of (%d+)") or "0") or 0
    assert(registered >= 50,
           "gcpkg: lyra: expected the whole upstream suite, ctest ran " .. registered)
end

-- upstream's own external-project check: tests/lib_use_test does
-- find_package(lyra REQUIRED) and links bfg::lyra from the installed tree.
local function run_lib_use_test(ctx)
    local src = util.join(ctx.src, "tests", "lib_use_test")
    local build = util.join(ctx.build_dir, "lib-use-test")
    ctx.exec({ "cmake", "-S", src, "-B", build,
               "-DCMAKE_BUILD_TYPE=Release",
               "-DCMAKE_CXX_COMPILER=" .. tostring(ctx.compiler.wrapper_cxx),
               "-DCMAKE_PREFIX_PATH=" .. tostring(ctx.prefix),
               -- upstream's consumer project says cmake_minimum_required(3.0),
               -- which CMake  >= 4 refuses outright; this is the documented
               -- escape hatch and only relaxes that one policy check.
               "-DCMAKE_POLICY_VERSION_MINIMUM=3.5" },
             { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
    ctx.exec({ "cmake", "--build", build, "--parallel", tostring(ctx.jobs or 4) },
             { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
    local out = util.join(ctx.build_dir, "lib-use-test.out")
    ctx.exec({ "sh", "-c",
               "cd " .. build .. " && ctest --output-on-failure > " .. out ..
               " 2>&1; echo $? >> " .. out },
             { cwd = build, log = ctx.log, env = ctx.env })
    local text = assert(fs.read(out), "gcpkg: lyra: missing lib_use_test output")
    assert(text:find("100% tests passed", 1, true),
           "gcpkg: lyra: tests/lib_use_test did not pass: " .. text)
end

return recipe.cmake {
    name = "lyra",
    version = VERSION,
    license = "BSL-1.0",
    homepage = "https://github.com/bfgroup/Lyra",
    description = "A simple to use, composing, header-only command line argument parser for C++11 and later",
    source = {
        url = "https://codeload.github.com/bfgroup/Lyra/tar.gz/refs/tags/1.7.0",
        sha256 = "d26b9e9dc1e08f88feaebc68965a6e5b25c7cd88617ce910d47cc83efb1e07d9",
        strip = 1,
    },
    dependencies = {},
    cmake = {
        defines = {
            CMAKE_INSTALL_INCLUDEDIR = "include",
            CMAKE_INSTALL_LIBDIR = "lib",
        },
    },
    post_install = function(ctx)
        local on = ctx.features.enabled
        local incdir = util.join(ctx.prefix, "include")
        local libdir = util.join(ctx.prefix, "lib")
        local docdir = util.join(ctx.prefix, "share", "doc", "lyra")
        fs.mkdirs(docdir)

        for _, h in ipairs({ "lyra/lyra.hpp", "lyra/cli.hpp", "lyra/args.hpp",
                             "lyra/opt.hpp", "lyra/version.hpp" }) do
            assert(fs.isfile(util.join(incdir, h)),
                   "gcpkg: lyra: " .. h .. " missing from the install tree")
        end

        if on["cmake-package"] then
            for _, pat in ipairs({ "share/lyra/cmake/lyraConfig.cmake",
                                   "share/lyra/cmake/lyraTarget.cmake" }) do
                assert(fs.isfile(util.join(ctx.prefix, pat)),
                       "gcpkg: lyra: upstream " .. pat .. " missing")
            end
        end

        if on["pkgconfig"] then
            local pcdir = util.join(libdir, "pkgconfig")
            fs.mkdirs(pcdir)
            fs.write(util.join(pcdir, "lyra.pc"), table.concat({
                "prefix=" .. tostring(ctx.prefix),
                "includedir=" .. tostring(incdir),
                "libdir=" .. tostring(libdir),
                "",
                "Name: Lyra",
                "Description: A simple to use, composing, header only, command line arguments parser for C++ 11 and beyond.",
                "Version: " .. VERSION,
                "Cflags: -I${includedir}",
                "",
            }, "\n"))
        end

        if on["tests"] then
            run_upstream_tests(ctx)
        end
        if on["lib-use-test"] then
            assert(on["cmake-package"],
                   "gcpkg: lyra: lib-use-test needs cmake-package (it uses find_package)")
            run_lib_use_test(ctx)
        end

        if on["docs"] then
            for _, f in ipairs({ "README.adoc", "CONTRIBUTING.adoc" }) do
                if fs.isfile(util.join(ctx.src, f)) then
                    ctx.exec({ "cp", "-a", util.join(ctx.src, f), docdir },
                             { cwd = ctx.src, log = ctx.log })
                end
            end
            if fs.isdir(util.join(ctx.src, "docs")) then
                ctx.exec({ "cp", "-a", util.join(ctx.src, "docs"), docdir },
                         { cwd = ctx.src, log = ctx.log })
            end
        end
        if on["license"] then
            assert(fs.isfile(util.join(ctx.src, "LICENSE.txt")),
                   "gcpkg: lyra: LICENSE.txt missing")
            ctx.exec({ "cp", "-a", util.join(ctx.src, "LICENSE.txt"), docdir },
                     { cwd = ctx.src, log = ctx.log })
        end

        if on["sanity"] then
            local csrc = util.join(ctx.build_dir, "lyra_sanity.cpp")
            fs.write(csrc, [==[
#include <lyra/lyra.hpp>
#include <cstdio>
#include <sstream>
#include <string>

int main() {
  std::string value;
  int verbose = 0;
  bool show_help = false;
  auto cli = lyra::cli() | lyra::help(show_help) |
             lyra::opt(value, "value")["-v"]["--value"]("value") |
             lyra::opt([&](bool) { verbose += 1; })["-V"]["--verbose"]
                 .cardinality(0, 3)("verbose");
  const char *argv1[] = {"app", "-v", "hello", "-V", "-V"};
  auto r1 = cli.parse({5, const_cast<char **>(argv1)});
  if (!r1) return 2;
  if (value != "hello") return 3;
  if (verbose != 2) return 4;
  // an unknown option must be refused
  const char *argv2[] = {"app", "--nope"};
  auto r2 = cli.parse({2, const_cast<char **>(argv2)});
  if (r2) return 5;
  // -h must set the help flag, and the usage text must render
  const char *argv3[] = {"app", "-h"};
  auto r3 = cli.parse({2, const_cast<char **>(argv3)});
  if (!r3) return 6;
  if (!show_help) return 7;
  std::ostringstream usage;
  usage << cli;
  if (usage.str().find("--value") == std::string::npos) return 8;
  std::printf("gcpkg lyra ok value=%s verbose=%d version=%d\n", value.c_str(),
              verbose, LYRA_VERSION_MAJOR);
  return 0;
}
]==])
            local exe = util.join(ctx.build_dir, "lyra_sanity")
            cc.executable {
                sources = { csrc },
                includes = { incdir },
                flags = { "-std=c++17" },
                cwd = ctx.build_dir,
                outdir = util.join(ctx.build_dir, "obj_sanity"),
                compiler = ctx.compiler.wrapper_cxx,
                exec = ctx.exec, record = ctx.record, log = ctx.log,
                tag = "lyra", cxx = true, output = exe,
                libdirs = {}, libs = {},
            }
            local out = util.join(ctx.build_dir, "sanity.out")
            ctx.exec({ "sh", "-c", exe .. " > " .. out .. " 2>&1" },
                     { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
            local text = assert(fs.read(out), "gcpkg: lyra: missing sanity output")
            assert(text:find("gcpkg lyra ok", 1, true),
                   "gcpkg: lyra: consumer did not run: " .. text)
        end
    end,
    exports = {
        includes = { "@PREFIX@/include" },
        libdirs = {},
        libs = {},
        binaries = {},
    },
}
