-- lua 5.4.7 -- gcpkg port definition.
-- lua.org is not reachable through the configured proxy, so this port builds
-- the official lua/lua GitHub mirror's development makefile instead. CC is
-- forced to gcpkg-intercept so compdb is produced.

local util = require("gcpkg.util")
local fs = require("gcpkg.fs")

return {
    name = "lua",
    version = "5.4.7",
    description = "Lua 5.4 interpreter and embeddable liblua",
    license = "MIT",
    homepage = "https://www.lua.org",
    source = {
        url = "https://github.com/lua/lua/archive/refs/tags/v5.4.7.tar.gz",
        sha256 = "5c39111b3fc4c1c9e56671008955a1730f54a15b95e1f1bd0752b868b929d8e3",
        strip = 1,
    },
    dependencies = {},
    build = function(ctx)
        local j = tostring(ctx.jobs or 4)
        local cc = ctx.env.CC
        -- The mirror's lowercase makefile has an "all" file checked in, so
        -- request the real artefacts rather than the "all" target.
        ctx.exec({ "make", "-j" .. j, "-f", "makefile", "liblua.a", "lua",
                   "CC=" .. cc,
                   "CFLAGS=-O2 -fPIC -DLUA_USE_LINUX -Wall",
                   "MYLDFLAGS=", "MYLIBS=-ldl",
                   "CWARNS=", "CWARNSCPP=", "CWARNSC=", "CWARNGCC=" },
                 { cwd = ctx.src, log = ctx.log })
        local incdir = util.join(ctx.prefix, "include")
        local libdir = util.join(ctx.prefix, "lib")
        local bindir = util.join(ctx.prefix, "bin")
        fs.mkdirs(incdir)
        fs.mkdirs(libdir)
        fs.mkdirs(bindir)
        for _, name in ipairs(fs.listdir(ctx.src) or {}) do
            if util.endswith(name, ".h") then
                ctx.exec({ "cp", "-a", util.join(ctx.src, name), incdir },
                         { cwd = ctx.src, log = ctx.log })
            end
        end
        fs.write(util.join(incdir, "lua.hpp"), [[// C++ wrapper generated by the gcpkg lua port.
extern "C" {
#include "lua.h"
#include "lauxlib.h"
#include "lualib.h"
}
]])
        ctx.exec({ "cp", "-a", util.join(ctx.src, "liblua.a"), libdir },
                 { cwd = ctx.src, log = ctx.log })
        ctx.exec({ "cp", "-a", util.join(ctx.src, "lua"), bindir },
                 { cwd = ctx.src, log = ctx.log })
        return {
            includes = { incdir },
            libdirs = { libdir },
            libs = { "lua" },
            binaries = { bindir },
        }
    end,
}
