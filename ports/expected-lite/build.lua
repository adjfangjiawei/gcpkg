-- expected-lite v0.8.0 -- R20 new-standard header-only port.
-- Upstream is a real CMake project with a bundled test framework (lest): the
-- port does not replace it with a synthetic probe.  Every upstream option is a
-- feature and defaults ON (features.yaml args are appended last and win via
-- dedup_defines); the default-ON state is verified afterwards by running the
-- upstream ctest suite and a real consumer against the installed tree.
local recipe = require("gcpkg.recipe")
local fs = require("gcpkg.fs")
local util = require("gcpkg.util")
local cc = require("gcpkg.build.cc")

return recipe.cmake {
    name = "expected-lite",
    version = "v0.8.0",
    license = "BSL-1.0",
    homepage = "https://github.com/martinmoene/expected-lite",
    description = "C++23 std::expected backport",
    source = {
        url = "https://codeload.github.com/martinmoene/expected-lite/tar.gz/refs/tags/v0.8.0",
        sha256 = "27649f30bd9d4fe7b193ab3eb6f78c64d0f585c24c085f340b4722b3d0b5e701",
        strip = 1,
    },
    dependencies = {},
    cmake = {
        -- Every switch is declared OFF here and turned ON by features.yaml,
        -- so the feature really drives the build instead of being decoration.
        defines = {
            EXPECTED_LITE_OPT_BUILD_TESTS = "OFF",
            EXPECTED_LITE_OPT_BUILD_EXAMPLES = "OFF",
            EXPECTED_LITE_OPT_SELECT_STD = "OFF",
            EXPECTED_LITE_OPT_SELECT_NONSTD = "OFF",
            CMAKE_INSTALL_INCLUDEDIR = "include",
            CMAKE_INSTALL_LIBDIR = "lib",
        },
    },
    pre_build = function(ctx)
        if ctx.features.enabled["examples"] then
            local exdir = util.join(ctx.src, "example")
            local cml = util.join(exdir, "CMakeLists.txt")
            local marker = "# generated by the gcpkg port"
            local existing = fs.isfile(cml) and (fs.read(cml) or "") or ""
            -- Upstream example/CMakeLists.txt at this tag cannot build all of
            -- its own examples (see the notes in features.yaml).  The port
            -- provides the example build file instead of silently dropping
            -- the examples feature:
            if fs.isdir(exdir) and
                   (existing == "" or existing:find(marker, 1, true) ~= nil) then
                local out = { marker,
                              "cmake_minimum_required(VERSION 3.8)",
                              "project(gcpkg_examples LANGUAGES CXX)",
                              "set(CMAKE_CXX_STANDARD 14)",
                              "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
                              "set(CMAKE_CXX_EXTENSIONS OFF)" }
                out[#out + 1] = "include_directories(\"" .. util.join(ctx.src, "include") .. "\")"
                out[#out + 1] = "add_executable(01-basic 01-basic.cpp)"
                out[#out + 1] = "target_compile_features(01-basic PRIVATE cxx_std_14)"
                out[#out + 1] = "add_executable(02-required 02-required.cpp)"
                out[#out + 1] = "target_compile_features(02-required PRIVATE cxx_std_14)"
                out[#out + 1] = "add_executable(03-no-exceptions 03-no-exceptions.cpp)"
                out[#out + 1] = "target_compile_features(03-no-exceptions PRIVATE cxx_std_14)"
                fs.write(cml, table.concat(out, "\n") .. "\n")
            end
        end
    end,
    post_install = function(ctx)
        local on = ctx.features.enabled
        local incdir = util.join(ctx.prefix, "include")
        local libdir = util.join(ctx.prefix, "lib")
        local docdir = util.join(ctx.prefix, "share", "doc", "expected-lite")
        fs.mkdirs(docdir)

        if on["headers"] then
            assert(fs.isfile(util.join(incdir, "nonstd/expected.hpp")),
                   "gcpkg: expected-lite: nonstd/expected.hpp missing")
        end

        -- docs / license: real upstream files
        if on["docs"] then
            for _, f in ipairs({ "README.md", "CHANGES.txt", "Notes.md", }) do
                if fs.isfile(util.join(ctx.src, f)) then
                    ctx.exec({ "cp", "-a", util.join(ctx.src, f), docdir },
                             { cwd = ctx.src, log = ctx.log })
                end
            end
        end
        if on["license"] then
            for _, f in ipairs({ "LICENSE.txt", }) do
                assert(fs.isfile(util.join(ctx.src, f)),
                       "gcpkg: expected-lite: " .. f .. " missing")
                ctx.exec({ "cp", "-a", util.join(ctx.src, f), docdir },
                         { cwd = ctx.src, log = ctx.log })
            end
        end

        -- pkg-config metadata for the installed headers
        if on["pkgconfig"] then
            local pcdir = util.join(libdir, "pkgconfig")
            fs.mkdirs(pcdir)
            local pc = [==[
prefix=@PREFIX@
exec_prefix=${prefix}
includedir=${prefix}/include

Name: expected-lite
Description: C++23 std::expected backport
Version: v0.8.0
Cflags: -I${includedir}
]==]
            fs.write(util.join(pcdir, "expected-lite.pc"), (pc:gsub("@PREFIX@", ctx.prefix)))
        end

        -- upstream package configuration (find_package(expected-lite CONFIG))
        if on["cmake-package"] then
            local found = false
            for _, pat in ipairs({ "lib/cmake/expected-lite", "share/cmake/expected-lite",
                                   "lib/expected-lite" }) do
                if fs.isdir(util.join(ctx.prefix, pat)) then found = true break end
            end
            assert(found, "gcpkg: expected-lite: upstream package configuration missing")
        end

        -- upstream test suite: real executables, really executed
        if on["tests"] then
            local out = util.join(ctx.build_dir, "ctest.out")
            ctx.exec({ "sh", "-c", "ctest --output-on-failure > " .. out .. " 2>&1" },
                     { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
            local text = assert(fs.read(out),
                                "gcpkg: expected-lite: missing ctest output")
            assert(not text:find("No tests were found", 1, true),
                   "gcpkg: expected-lite: ctest found no registered tests")
            assert(text:find("100% tests passed", 1, true),
                   "gcpkg: expected-lite: upstream test suite did not pass: " .. text)
        end

        -- examples: upstream CMake builds them; the built programs are RUN and
        -- their exit status is checked.  A handful of upstream examples exist
        -- only to demonstrate an aborting failure mode (e.g. 03-no-exceptions terminates by design when the error path is hit); those
        -- are allowed to die, every other example must exit 0.
        if on["examples"] then
            local exdir = util.join(ctx.build_dir, "example")
            local demos = { "03-no-exceptions" }
            local ran, ok_ran, notes, wrong = 0, 0, {}, {}
            local env = ctx.env or {}
            env.LD_LIBRARY_PATH = util.join(ctx.prefix, "lib") ..
                (env.LD_LIBRARY_PATH and (":" .. env.LD_LIBRARY_PATH) or "")
            local function is_demo(f)
                for _, d in ipairs(demos) do if d == f then return true end end
                return false
            end
            for _, f in ipairs(fs.listdir(exdir)) do
                local p = util.join(exdir, f)
                if not fs.isdir(p) and not f:match("%.cmake$") and
                   not f:match("^Makefile$") and not f:match("^cmake_install") then
                    local out = util.join(ctx.build_dir, "example-" .. f .. ".out")
                    local rc = "?"
                    local script = p .. " > " .. out .. " 2>&1; echo $? > " ..
                                   out .. ".rc"
                    pcall(function()
                        ctx.exec({ "sh", "-c", script },
                                 { cwd = ctx.build_dir, log = ctx.log, env = env })
                    end)
                    rc = (fs.read(out .. ".rc") or "?"):gsub("%s", "")
                    ran = ran + 1
                    if rc == "0" then
                        ok_ran = ok_ran + 1
                    elseif not is_demo(f) then
                        wrong[#wrong + 1] = f .. " rc=" .. rc
                    end
                    notes[#notes + 1] = f .. " rc=" .. rc ..
                        (is_demo(f) and " (expected: upstream demo terminates itself)" or "")
                end
            end
            fs.write(util.join(ctx.build_dir, "examples.out"),
                     table.concat(notes, "\n") .. "\n")
            assert(ran > 0,
                   "gcpkg: expected-lite: examples feature is on but no example program was built")
            assert(ok_ran > 0,
                   "gcpkg: expected-lite: no example program completed successfully: " ..
                   table.concat(notes, ", "))
            assert(#wrong == 0,
                   "gcpkg: expected-lite: example program(s) failed: " .. table.concat(wrong, ", "))
        end

        -- sanity: real consumer over the INSTALLED headers
        if on["sanity"] then
            local csrc = util.join(ctx.build_dir, "expected-lite_sanity.cpp")
            fs.write(csrc, [==[
#include <nonstd/expected.hpp>
#include <cstdio>
#include <string>

static nonstd::expected<int, std::string> half(int v) {
  if (v % 2) return nonstd::make_unexpected(std::string("odd"));
  return v / 2;
}

int main() {
  auto good = half(84);
  if (!good || good.value() != 42) return 2;
  auto bad = half(7);
  if (bad || bad.error() != "odd") return 3;
  std::printf("gcpkg expected-lite ok value=%d error=%s\n", good.value(),
              bad.error().c_str());
  return 0;
}
]==])
            local exe = util.join(ctx.build_dir, "expected-lite_sanity")
            cc.executable {
                sources = { csrc },
                includes = { incdir },
                flags = { "-std=c++17" },
                cwd = ctx.build_dir,
                outdir = util.join(ctx.build_dir, "obj_sanity"),
                compiler = ctx.compiler.wrapper_cxx,
                exec = ctx.exec, record = ctx.record, log = ctx.log,
                tag = "expected-lite", cxx = true, output = exe,
                libdirs = {}, libs = {},
            }
            local out = util.join(ctx.build_dir, "sanity.out")
            ctx.exec({ "sh", "-c", exe .. " > " .. out .. " 2>&1" },
                     { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
            local text = assert(fs.read(out), "gcpkg: expected-lite: missing sanity output")
            assert(text:find("gcpkg expected-lite ok", 1, true),
                   "gcpkg: expected-lite: consumer did not run: " .. text)
        end
    end,
    exports = {
        includes = { "@PREFIX@/include" },
        libdirs = {},
        libs = {},
        binaries = {},
    },
}
