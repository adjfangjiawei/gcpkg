-- spirv-headers (vulkan-sdk-1.4.363.0) -- R20 new-standard header-only port.
-- The Khronos SPIR-V headers.  Upstream is a real CMake project with two
-- options and a genuine small test suite (tests/: the same tiny program built
-- three times - C99, C++98 and C++11 - with SPV_ENABLE_UTILITY_CODE, exercising
-- the header's enum/utility code and its C/C++ compatibility).
--
-- Upstream switch surface (CMakeLists.txt):
--   SPIRV_HEADERS_ENABLE_TESTS   -> feature `tests`
--   SPIRV_HEADERS_ENABLE_INSTALL -> feature `install`  (headers + CONFIG package
--                                   + generated SPIRV-Headers.pc)
-- Both default ON (upstream defaults them to PROJECT_IS_TOP_LEVEL) and each has
-- an explicit `no-*` twin.
local recipe = require("gcpkg.recipe")
local fs = require("gcpkg.fs")
local util = require("gcpkg.util")
local cc = require("gcpkg.build.cc")

-- Upstream registers three add_test() entries in tests/CMakeLists.txt but never
-- calls enable_testing() anywhere in the project, so a stock configure emits no
-- CTestTestfile.cmake at all and `ctest` reports "No tests were found".  The
-- real programs are the point: they are the same tiny consumer built as C99,
-- C++98 and C++11.  We therefore hand CMake a tiny extra top-level include
-- (CMAKE_PROJECT_TOP_LEVEL_INCLUDES, cmake >= 3.24) that calls enable_testing()
-- right after project(SPIRV-Headers) so the upstream test targets register with
-- CTest and run through ctest, not through a hand-rolled driver.
local function testing_shim(ctx)
    local f = util.join(ctx.build_dir, "gcpkg-enable-testing.cmake")
    fs.mkdirs(ctx.build_dir)
    fs.write(f, [[
# Generated by the gcpkg spirv-headers port.  Upstream ships add_test() entries
# but no enable_testing(), so this only turns CTest registration on; it does not
# add, skip or alter any test.
enable_testing()
]])
    return f
end

return recipe.cmake {
    name = "spirv-headers",
    version = "vulkan-sdk-1.4.363.0",
    license = "MIT",
    homepage = "https://github.com/KhronosGroup/SPIRV-Headers",
    description = "Khronos SPIR-V header files (unified1 C/C++ headers and JSON grammars)",
    source = {
        url = "https://codeload.github.com/KhronosGroup/SPIRV-Headers/tar.gz/refs/tags/vulkan-sdk-1.4.363.0",
        sha256 = "5b3a0d099f5c7649e29c0938476c462e71d66ad89a0bde42fa1ba3eb476956c9",
        strip = 1,
    },
    dependencies = {},
    -- pre_build is plain Lua and runs before configure; both options are driven
    -- by feature args (appended last, so they win over these defaults).
    pre_build = function(ctx)
        if ctx.features.enabled["tests"] then testing_shim(ctx) end
    end,
    cmake = {
        defines = function(ctx)
            local d = {
                SPIRV_HEADERS_ENABLE_TESTS = "OFF",
                SPIRV_HEADERS_ENABLE_INSTALL = "OFF",
                CMAKE_INSTALL_INCLUDEDIR = "include",
                CMAKE_INSTALL_LIBDIR = "lib",
            }
            if ctx.features.enabled["tests"] then
                d.CMAKE_PROJECT_TOP_LEVEL_INCLUDES = testing_shim(ctx)
            end
            return d
        end,
    },
    post_install = function(ctx)
        local on = ctx.features.enabled
        local incdir = util.join(ctx.prefix, "include")
        local docdir = util.join(ctx.prefix, "share", "doc", "spirv-headers")
        fs.mkdirs(docdir)

        if on["install"] then
            for _, h in ipairs({ "spirv/unified1/spirv.hpp", "spirv/unified1/spirv.h",
                                 "spirv/unified1/spirv.hpp11",
                                 "spirv/unified1/spirv.core.grammar.json",
                                 "spirv/unified1/extinst.glsl.std.450.grammar.json" }) do
                assert(fs.isfile(util.join(incdir, h)),
                       "gcpkg: spirv-headers: " .. h .. " missing from the install tree")
            end
        end

        -- tests: the three upstream test programs, really executed ----------
        if on["tests"] then
            local out = util.join(ctx.build_dir, "ctest.out")
            ctx.exec({ "sh", "-c",
                       "ctest --output-on-failure > " .. out .. " 2>&1; echo $? > " ..
                       out .. ".rc" },
                     { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
            local rc = (fs.read(out .. ".rc") or "?"):gsub("%s", "")
            local text = assert(fs.read(out), "gcpkg: spirv-headers: missing ctest output")
            assert(not text:find("No tests were found", 1, true),
                   "gcpkg: spirv-headers: ctest found no registered tests")
            assert(text:find("100% tests passed", 1, true),
                   "gcpkg: spirv-headers: upstream test suite did not pass: " .. text)
            assert(rc == "0", "gcpkg: spirv-headers: ctest exited with " .. rc)
            local registered = tonumber(text:match("out of (%d+)") or "0") or 0
            assert(registered == 3,
                   "gcpkg: spirv-headers: expected the three upstream test programs " ..
                   "(C, C++98, C++11), ctest ran " .. registered)
            for _, t in ipairs({ "spirv_headers_simple_test_c",
                                 "spirv_headers_simple_test_cpp11",
                                 "spirv_headers_simple_test" }) do
                assert(text:find(t, 1, true),
                       "gcpkg: spirv-headers: test " .. t .. " did not run: " .. text)
            end
        end

        -- CONFIG package + pkg-config: both are produced by upstream's own
        -- install rules, so assert them rather than generating our own.
        if on["cmake-package"] then
            assert(on["install"],
                   "gcpkg: spirv-headers: cmake-package needs the install feature")
            local found = false
            for _, pat in ipairs({ "share/cmake/SPIRV-Headers/SPIRV-HeadersConfig.cmake",
                                   "share/cmake/SPIRV-Headers/SPIRV-HeadersConfigVersion.cmake",
                                   "lib/cmake/SPIRV-Headers/SPIRV-HeadersConfig.cmake" }) do
                if fs.isfile(util.join(ctx.prefix, pat)) then found = true break end
            end
            assert(found, "gcpkg: spirv-headers: upstream CONFIG package missing")
        end
        if on["pkgconfig"] then
            assert(on["install"],
                   "gcpkg: spirv-headers: pkgconfig needs the install feature")
            local found = false
            for _, pat in ipairs({ "share/pkgconfig/SPIRV-Headers.pc",
                                   "lib/pkgconfig/SPIRV-Headers.pc" }) do
                if fs.isfile(util.join(ctx.prefix, pat)) then found = true break end
            end
            assert(found, "gcpkg: spirv-headers: upstream SPIRV-Headers.pc missing")
        end

        -- docs / license: upstream ships LICENSE plus a REUSE LICENSES/ tree --
        if on["docs"] then
            for _, f in ipairs({ "README.md", "CHANGES" }) do
                if fs.isfile(util.join(ctx.src, f)) then
                    ctx.exec({ "cp", "-a", util.join(ctx.src, f), docdir },
                             { cwd = ctx.src, log = ctx.log })
                end
            end
            for _, d in ipairs({ "docs" }) do
                if fs.isdir(util.join(ctx.src, d)) then
                    ctx.exec({ "cp", "-a", util.join(ctx.src, d), docdir },
                             { cwd = ctx.src, log = ctx.log })
                end
            end
        end
        if on["license"] then
            assert(fs.isfile(util.join(ctx.src, "LICENSE")),
                   "gcpkg: spirv-headers: LICENSE missing")
            ctx.exec({ "cp", "-a", util.join(ctx.src, "LICENSE"), docdir },
                     { cwd = ctx.src, log = ctx.log })
            if fs.isdir(util.join(ctx.src, "LICENSES")) then
                ctx.exec({ "cp", "-a", util.join(ctx.src, "LICENSES"), docdir },
                         { cwd = ctx.src, log = ctx.log })
            end
        end

        -- sanity: real consumer over the INSTALLED headers --------------------
        if on["sanity"] then
            assert(on["install"], "gcpkg: spirv-headers: sanity needs the install feature")
            local csrc = util.join(ctx.build_dir, "spirv_sanity.cpp")
            fs.write(csrc, [==[
#include <spirv/unified1/spirv.hpp>
#include <cstdio>

int main() {
  spv::Op op = spv::Op::OpTypeVoid;
  if (static_cast<int>(op) != 19) return 2;
  spv::ExecutionModel model = spv::ExecutionModel::ExecutionModelGLCompute;
  if (static_cast<int>(model) != 5) return 3;
  // opcode name helper comes from the header itself
  const char *name = spv::OpToString(op);
  if (name[0] == '\0') return 4;
  std::printf("gcpkg spirv-headers ok op=%s version=%d\n", name,
              (int)spv::Version);
  return 0;
}
]==])
            local exe = util.join(ctx.build_dir, "spirv_sanity")
            cc.executable {
                sources = { csrc },
                includes = { incdir },
                flags = { "-std=c++17", "-DSPV_ENABLE_UTILITY_CODE" },
                cwd = ctx.build_dir,
                outdir = util.join(ctx.build_dir, "obj_sanity"),
                compiler = ctx.compiler.wrapper_cxx,
                exec = ctx.exec, record = ctx.record, log = ctx.log,
                tag = "spirv-headers", cxx = true, output = exe,
                libdirs = {}, libs = {},
            }
            local out = util.join(ctx.build_dir, "sanity.out")
            ctx.exec({ "sh", "-c", exe .. " > " .. out .. " 2>&1" },
                     { cwd = ctx.build_dir, log = ctx.log, env = ctx.env })
            local text = assert(fs.read(out), "gcpkg: spirv-headers: missing sanity output")
            assert(text:find("gcpkg spirv-headers ok", 1, true),
                   "gcpkg: spirv-headers: consumer did not run: " .. text)
        end
    end,
    exports = {
        includes = { "@PREFIX@/include" },
        libdirs = {},
        libs = {},
        binaries = {},
    },
}
